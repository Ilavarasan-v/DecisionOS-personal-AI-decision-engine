from datetime import datetime
from typing import Any, Dict, List, Optional

from pydantic import BaseModel, ConfigDict, Field


class OptionCreate(BaseModel):
    """
    Candidate option supplied when creating a decision.
    """

    name: str = Field(
        ...,
        min_length=1,
        max_length=200,
    )

    description: Optional[str] = None

    attributes: Optional[Dict[str, Any]] = None


class OptionRead(BaseModel):
    """
    Candidate option returned by the API.
    """

    model_config = ConfigDict(from_attributes=True)

    id: str
    name: str
    description: Optional[str] = None
    attributes: Optional[Dict[str, Any]] = None

    # Populated after decision evaluation.
    score: Optional[float] = None


class DecisionCreate(BaseModel):
    """
    Payload used to create a new decision.
    """

    user_id: str = Field(
        ...,
        min_length=1,
    )

    title: str = Field(
        ...,
        min_length=1,
        max_length=200,
    )

    description: Optional[str] = None

    options: List[OptionCreate] = Field(
        default_factory=list,
    )


class DecisionRead(BaseModel):
    """
    Decision returned by the API.
    """

    model_config = ConfigDict(from_attributes=True)

    id: str
    user_id: str
    title: str
    description: Optional[str] = None
    status: str

    chosen_option_id: Optional[str] = None

    # Currently generated at response level.
    explanation: Optional[str] = None

    options: List[OptionRead] = Field(
        default_factory=list,
    )

    created_at: datetime

    # Currently mapped from created_at because the current
    # database model does not yet contain updated_at.
    updated_at: datetime


class TradeoffRead(BaseModel):
    """
    Strengths and weaknesses identified for an option
    from its criterion-level evaluation scores.
    """

    strengths: List[str] = Field(
        default_factory=list,
    )

    weaknesses: List[str] = Field(
        default_factory=list,
    )


class RankedOption(BaseModel):
    """
    A candidate option with its personalized ranking,
    score, and trade-off analysis.
    """

    option: OptionRead

    rank: int

    score: float

    # Reserved for the future AI reasoning layer.
    reasoning: Optional[str] = None

    # Deterministic trade-off analysis generated by
    # the DecisionOS evaluation layer.
    tradeoffs: TradeoffRead = Field(
        default_factory=TradeoffRead,
    )


class DecisionResult(BaseModel):
    """
    Final decision evaluation response.
    """

    decision_id: str

    ranked_options: List[RankedOption]

    recommendation: OptionRead

    explanation: str